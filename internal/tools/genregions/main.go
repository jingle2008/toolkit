// Command genregions writes pkg/models' map of OCI region short codes
// from the OCI Go SDK the module depends on: its common/regions.go
// declares each region as a constant and maps short codes to them
// (shortNameRegion), but exports neither the map nor its reverse.
//
// Run through go generate in pkg/models after bumping the SDK.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const sdkModule = "github.com/oracle/oci-go-sdk/v65"

func main() {
	out := flag.String("o", "regions_sdk.go", "file to write")
	flag.Parse()
	if err := run(*out); err != nil {
		log.Fatal(err)
	}
}

func run(out string) error {
	dir, version, err := sdkDir()
	if err != nil {
		return err
	}
	codes, err := shortNames(filepath.Join(dir, "common", "regions.go"))
	if err != nil {
		return err
	}
	src, err := render(codes, version)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}

// sdkDir is where the module's SDK version lives, and that version.
func sdkDir() (dir, version string, err error) {
	b, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", sdkModule).Output()
	if err != nil {
		return "", "", fmt.Errorf("locate %s: %w", sdkModule, err)
	}
	dir, version, ok := strings.Cut(strings.TrimSpace(string(b)), " ")
	if !ok || dir == "" {
		return "", "", fmt.Errorf("locate %s: unexpected %q", sdkModule, b)
	}
	return dir, version, nil
}

// shortNames reads the SDK's shortNameRegion map, resolving each
// constant to its region identifier.
func shortNames(path string) (map[string]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	consts, table := declarations(f)
	if table == nil {
		return nil, errors.New("shortNameRegion not found: the SDK's layout changed")
	}
	return resolve(table, consts)
}

// declarations collects f's string constants by name, and its
// shortNameRegion map literal (nil when there is none).
func declarations(f *ast.File) (consts map[string]string, table *ast.CompositeLit) {
	consts = map[string]string{}
	ast.Inspect(f, func(n ast.Node) bool {
		spec, ok := n.(*ast.ValueSpec)
		if !ok {
			return true
		}
		for i, name := range spec.Names {
			if i >= len(spec.Values) {
				break
			}
			switch v := spec.Values[i].(type) {
			case *ast.BasicLit:
				if s, err := strconv.Unquote(v.Value); err == nil {
					consts[name.Name] = s
				}
			case *ast.CompositeLit:
				if name.Name == "shortNameRegion" {
					table = v
				}
			}
		}
		return true
	})
	return consts, table
}

// resolve maps table's short codes to the regions its constants name.
func resolve(table *ast.CompositeLit, consts map[string]string) (map[string]string, error) {
	codes := map[string]string{}
	for _, elt := range table.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, kok := kv.Key.(*ast.BasicLit)
		val, vok := kv.Value.(*ast.Ident)
		if !kok || !vok {
			return nil, fmt.Errorf("unexpected shortNameRegion entry at %v", kv.Pos())
		}
		code, err := strconv.Unquote(key.Value)
		if err != nil {
			return nil, err
		}
		region, ok := consts[val.Name]
		if !ok {
			return nil, fmt.Errorf("short code %q names unknown constant %s", code, val.Name)
		}
		codes[code] = region
	}
	return codes, nil
}

// render is the generated Go file for codes.
func render(codes map[string]string, version string) ([]byte, error) {
	keys := make([]string, 0, len(codes))
	for k := range codes {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genregions from %s %s; DO NOT EDIT.\n\n", sdkModule, version)
	b.WriteString("package models\n\n")
	b.WriteString("// sdkShortNames are the OCI SDK's region short codes.\n")
	b.WriteString("var sdkShortNames = map[string]Region{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, codes[k])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
